import { test, expect } from "@playwright/test";
import { chooseOption } from "../helpers/chooseOption";

test.afterEach(async ({ page }) => { await page.unrouteAll({ behavior: "ignoreErrors" }); });

test("independent annotations stage without a save and custom navigation guards preserve the review", async ({ page }) => {
  const errors: string[] = [];
  let reviewWrites = 0;
  page.on("pageerror", error => errors.push(error.message));
  await page.route("**/api/v1/**", async route => {
    if (route.request().method() === "PUT" && /\/review(?:\?|$)/.test(route.request().url())) reviewWrites++;
    const url = new URL(route.request().url()); url.port = "8015";
    await route.fulfill({ response: await route.fetch({ url: url.toString() }) });
  });
  await page.request.post("http://127.0.0.1:8015/api/v1/test/login");
  const before = await (await page.request.get("http://127.0.0.1:8015/api/v1/corpus")).json();
  expect(before.annotation_pilot.state).toBe("READY");
  const selected = before.annotation_pilot.queue.find((row: { audit_selection: string | null }) => row.audit_selection);
  expect(selected).toBeTruthy();
  const detail = await (await page.request.get(`http://127.0.0.1:8015/api/v1/corpus/repos/${selected.repository_id}`)).json();
  await page.goto("/");
  await chooseOption(page.getByLabel("Workspace collection"), "ground-truth");
  await page.getByRole("button", { name: /^Annotation pilot/ }).click();
  const pilot = page.getByRole("dialog", { name: "Independent annotation pilot", exact: true });
  await pilot.getByRole("button", { name: `Review ${selected.full_name}`, exact: true }).click();
  const review = page.getByRole("region", { name: "Repository evidence review", exact: true });
  await expect(review.getByRole("heading", { name: selected.full_name, exact: true })).toBeVisible();
  const inputs = review.getByRole("region", { name: "Agent A and B inputs", exact: true });
  await expect(inputs).toBeVisible();
  for (const key of ["a", "b"] as const) {
    const input = inputs.getByRole("article", { name: `Agent ${key.toUpperCase()} summary`, exact: true });
    await expect(input).toContainText(detail.annotation_pilot.record.annotations[key].purpose);
    for (const id of detail.annotation_pilot.record.annotations[key].positive_ids) {
      await expect(input.getByText(before.registry.find((concept: { id: string }) => concept.id === id).name, { exact: true })).toBeVisible();
    }
  }
  await review.getByRole("button", { name: "Compare independent annotations", exact: true }).click();
  const comparison = page.getByRole("region", { name: "Independent agent annotations", exact: true });
  await expect(comparison).toContainText("Annotator A");
  await expect(comparison).toContainText("Annotator B");
  await expect(comparison).toContainText("Agreed labels");
  await expect(comparison).toContainText("Unlisted labels remain unknown");
  await page.screenshot({ path: "test-results-corpus/agent-annotation-comparison-1080p.png", fullPage: false });
  await page.getByRole("button", { name: "Close comparison", exact: true }).click();
  expect(detail.files.some((file: { path: string }) => file.path === "@github-metadata.json")).toBeTruthy();
  await chooseOption(page.getByLabel("Source document", { exact: true }), "@github-metadata.json");
  await expect(page.getByLabel("Saved source text", { exact: true })).toContainText('"primary_language"');
  const sourceChoice = page.getByRole("combobox", { name: "Source document", exact: true });
  const pinnedLabel = await sourceChoice.inputValue();
  await sourceChoice.fill("uncommitted source search");
  await sourceChoice.press("Tab");
  await expect(sourceChoice).toHaveValue(pinnedLabel);
  await expect(page.getByRole("region", { name: "Saved source evidence", exact: true })).toContainText("Pinned public GitHub metadata");
  await review.getByRole("button", { name: "Compare independent annotations", exact: true }).click();
  await comparison.getByRole("button", { name: "Stage annotator A in my review", exact: true }).click();
  await expect(page.getByRole("dialog", { name: "Independent annotations", exact: true })).not.toBeVisible();
  await expect(review.getByLabel("Repository purpose", { exact: true })).toHaveValue(detail.annotation_pilot.record.annotations.a.purpose);
  for (const kind of ["Projects", "Topics", "Tags"]) await expect(review.getByRole("checkbox", { name: `${kind} reviewed`, exact: true })).not.toBeChecked();
  await expect(page.getByRole("status")).toContainText("not saved");
  await review.getByRole("checkbox", { name: "Topics reviewed", exact: true }).check();
  const topics = review.getByRole("region", { name: "Topic labels", exact: true }).getByRole("button", { name: /^Remove topic / });
  const topicCount = await topics.count();
  expect(topicCount).toBeGreaterThan(0);
  await topics.first().click();
  await expect(topics).toHaveCount(topicCount - 1);
  await expect(review.getByRole("checkbox", { name: "Topics reviewed", exact: true })).not.toBeChecked();
  expect(reviewWrites).toBe(0);
  const after = await (await page.request.get("http://127.0.0.1:8015/api/v1/corpus")).json();
  expect(after.human_confirmed).toBe(before.human_confirmed);
  expect(after.reviewed).toBe(before.reviewed);
  await chooseOption(page.getByLabel("Workspace collection"), "github");
  const leave = page.getByRole("dialog", { name: "Save your changes?", exact: true });
  await expect(leave).toBeVisible();
  await leave.getByRole("button", { name: "Stay", exact: true }).click();
  await expect(page.getByRole("combobox", { name: "Workspace collection", exact: true })).toHaveValue("Public - Ground Truth");
  await expect(review.getByLabel("Repository purpose", { exact: true })).toHaveValue(detail.annotation_pilot.record.annotations.a.purpose);
  await review.getByRole("button", { name: "Close review", exact: true }).click();
  await leave.getByRole("button", { name: "Stay", exact: true }).click();
  await expect(review.getByLabel("Repository purpose", { exact: true })).toHaveValue(detail.annotation_pilot.record.annotations.a.purpose);
  await page.screenshot({ path: "test-results-corpus/agent-annotation-staged-review-1080p.png", fullPage: false });
  await review.getByRole("button", { name: "Close review", exact: true }).click();
  await leave.getByRole("button", { name: "Discard changes", exact: true }).click();
  await expect(review.getByRole("heading", { name: "Select a repository", exact: true })).toBeVisible();
  expect(reviewWrites).toBe(0);
  expect(errors).toEqual([]);
});

test("nonpilot coverage is explicit and Agent A/B inputs stay discoverable on mobile without replacing a saved draft", async ({ page }) => {
  const errors: string[] = [];
  let writes = 0;
  page.on("pageerror", error => errors.push(error.message));
  await page.route("**/api/v1/**", async route => {
    if (route.request().method() === "PUT") writes++;
    const url = new URL(route.request().url()); url.port = "8015";
    await route.fulfill({ response: await route.fetch({ url: url.toString() }) });
  });
  await page.request.post("http://127.0.0.1:8015/api/v1/test/login");
  const summary = await (await page.request.get("http://127.0.0.1:8015/api/v1/corpus")).json();
  const rows = await (await page.request.get("http://127.0.0.1:8015/api/v1/corpus/repos?limit=25")).json();
  const pilotIds = new Set(summary.annotation_pilot.queue.map((row: { repository_id: number }) => row.repository_id));
  const nonpilot = rows.items.find((row: { repository_id: number }) => !pilotIds.has(row.repository_id));
  expect(nonpilot).toBeTruthy();
  await page.goto("/");
  await chooseOption(page.getByLabel("Workspace collection"), "ground-truth");
  await page.getByRole("button", { name: `Review ${nonpilot.full_name}`, exact: true }).click();
  const review = page.getByRole("region", { name: "Repository evidence review", exact: true });
  await expect(review.getByRole("heading", { name: nonpilot.full_name, exact: true })).toBeVisible();
  const availability = review.getByRole("region", { name: "Agent annotation availability", exact: true });
  await expect(availability).toContainText("No Agent A/B annotations for this repository");
  await expect(availability).toContainText(`covers ${pilotIds.size} of ${summary.total} repositories`);
  await expect(review.getByRole("button", { name: "Compare independent annotations", exact: true })).toHaveCount(0);
  await page.screenshot({ path: "test-results-corpus/agent-inputs-nonpilot-1920.png" });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(availability.getByRole("button", { name: /^Open Agent A\/B pilot queue/ })).toBeVisible();
  await page.screenshot({ path: "test-results-corpus/agent-inputs-nonpilot-390.png" });
  await availability.getByRole("button", { name: /^Open Agent A\/B pilot queue/ }).click();
  const selected = summary.annotation_pilot.queue.find((row: { audit_selection: string | null }) => row.audit_selection);
  const pilot = page.getByRole("dialog", { name: "Independent annotation pilot", exact: true });
  await pilot.getByRole("button", { name: `Review ${selected.full_name}`, exact: true }).click();
  await expect(review.getByRole("heading", { name: selected.full_name, exact: true })).toBeVisible();
  const inputs = review.getByRole("region", { name: "Agent A and B inputs", exact: true });
  await expect(inputs.getByRole("article", { name: "Agent A summary", exact: true }).getByRole("heading")).toBeVisible();
  await expect(inputs.getByRole("article", { name: "Agent B summary", exact: true })).toBeAttached();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: "test-results-corpus/agent-inputs-pilot-390.png" });
  await inputs.getByRole("button", { name: "Compare independent annotations", exact: true }).click();
  const comparison = page.getByRole("dialog", { name: "Independent annotations", exact: true });
  await expect(comparison).toBeVisible();
  await expect(comparison.getByRole("heading", { name: "Annotator A", exact: true })).toBeVisible();
  await expect(comparison.getByRole("heading", { name: "Annotator B", exact: true })).toBeAttached();
  await page.getByRole("button", { name: "Close comparison", exact: true }).click();
  expect(writes).toBe(0);
  await page.setViewportSize({ width: 1920, height: 1080 });
  const purpose = review.getByLabel("Repository purpose", { exact: true });
  await purpose.fill("Human draft remains unchanged when I inspect independent annotations.");
  await review.getByRole("button", { name: "Save draft", exact: true }).click();
  await expect(review).toContainText("Draft saved · revision");
  const writesAfterDraft = writes;
  await page.reload();
  await chooseOption(page.getByLabel("Workspace collection"), "ground-truth");
  await expect(review.getByLabel("Repository purpose", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: /^Annotation pilot/ }).click();
  await pilot.getByRole("button", { name: `Review ${selected.full_name}`, exact: true }).click();
  await expect(purpose).toHaveValue("Human draft remains unchanged when I inspect independent annotations.");
  await expect(review).toContainText("Your saved draft");
  await page.screenshot({ path: "test-results-corpus/agent-inputs-pilot-1920.png" });
  await inputs.getByRole("button", { name: "Compare independent annotations", exact: true }).click();
  await expect(comparison).toBeVisible();
  await page.screenshot({ path: "test-results-corpus/agent-inputs-comparison-1920.png" });
  await page.getByRole("button", { name: "Close comparison", exact: true }).click();
  await expect(purpose).toHaveValue("Human draft remains unchanged when I inspect independent annotations.");
  for (const kind of ["Projects", "Topics", "Tags"]) await expect(review.getByRole("checkbox", { name: `${kind} reviewed`, exact: true })).not.toBeChecked();
  expect(writes).toBe(writesAfterDraft);
  expect(errors).toEqual([]);
});

test("Confirm and next stays within the selected independent pilot queue and all corpus browsing remains available", async ({ page }) => {
  const neighborScopes: string[] = [];
  await page.route("**/api/v1/**", async route => {
    const url = new URL(route.request().url()); url.port = "8015";
    if (url.pathname.endsWith("/neighbors")) neighborScopes.push(url.searchParams.get("annotation_scope") || "");
    await route.fulfill({ response: await route.fetch({ url: url.toString() }) });
  });
  await page.request.post("http://127.0.0.1:8015/api/v1/test/login");
  const summary = await (await page.request.get("http://127.0.0.1:8015/api/v1/corpus")).json();
  const initial = summary.annotation_pilot.queue.filter((row: { audit_selection: string | null }) => row.audit_selection).sort((a: { full_name: string }, b: { full_name: string }) => a.full_name.toLowerCase().localeCompare(b.full_name.toLowerCase()));
  const selected = initial[0];
  await page.goto("/");
  await chooseOption(page.getByLabel("Workspace collection"), "ground-truth");
  const review = page.getByRole("region", { name: "Repository evidence review", exact: true });
  await expect(review.getByLabel("Repository purpose", { exact: true })).toBeVisible();
  await page.getByLabel("Search corpus repositories").fill("search-with-no-repository-matches");
  await expect(page.getByRole("region", { name: "Repository queue", exact: true })).toContainText("No repositories match");
  await page.getByRole("button", { name: /^Annotation pilot/ }).click();
  const pilot = page.getByRole("dialog", { name: "Independent annotation pilot", exact: true });
  await pilot.getByRole("button", { name: `Review ${selected.full_name}`, exact: true }).click();
  await expect(review.getByRole("heading", { name: selected.full_name, exact: true })).toBeVisible();
  await expect(page.getByLabel("Search corpus repositories")).toHaveValue("");
  const scope = page.getByRole("combobox", { name: "Repository review scope", exact: true });
  await expect(scope).toHaveValue(`Initial human review · ${initial.length}`);
  for (const kind of ["Projects", "Topics", "Tags"]) await review.getByRole("checkbox", { name: `${kind} reviewed`, exact: true }).check();
  await review.getByRole("button", { name: "Confirm & next", exact: true }).click();
  await expect(review.getByRole("heading", { name: initial[1].full_name, exact: true })).toBeVisible();
  await expect(review.getByRole("region", { name: "Agent A and B inputs", exact: true })).toBeVisible();
  expect(neighborScopes).toEqual(["initial_queue"]);
  await expect(scope).toHaveValue(`Initial human review · ${initial.length}`);
  const queue = page.getByRole("region", { name: "Repository queue", exact: true });
  await chooseOption(scope, "pilot");
  await expect(queue.getByText(`${summary.annotation_pilot.queue.length} results`, { exact: true }).first()).toBeVisible();
  await chooseOption(scope, "all");
  await expect(queue.getByText(`${summary.total} results`, { exact: true }).first()).toBeVisible();
});
