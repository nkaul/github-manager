// Local-only prototype smoke check; never opens the live app or an API.
const { chromium } = require('../../../frontend/node_modules/playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const { pathToFileURL } = require('node:url');
const url = pathToFileURL(path.join(__dirname, 'preview.html')).href;
(async () => {
 const browser = await chromium.launch({headless:true});
 const page = await browser.newPage({viewport:{width:1440,height:900},deviceScaleFactor:1});
 const errors=[],externalRequests=[],checks=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
 page.on('request',r=>{if(/^https?:/.test(r.url()))externalRequests.push(r.url())});
 page.on('dialog',d=>d.accept());
 await page.goto(url);
 for(const [width,height,name] of [[1920,1080,'desktop-1920.png'],[1440,900,'desktop-1440.png'],[390,844,'mobile-390.png'],[1024,768,null]]){
  await page.setViewportSize({width,height});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  if(name)await page.screenshot({path:path.join(__dirname,name)});
  checks.push(`${width}x${height}: no horizontal page overflow`);
 }
 await page.setViewportSize({width:1440,height:900});
 assert.equal(await page.locator('#confirm-next').isDisabled(),true);
 assert.equal(await page.locator('[data-dimension]:checked').count(),0);
 checks.push('confirmation disabled and all reviewed groups unchecked on open');
 await page.locator('#repo-search').fill('numpy');
 assert.equal(await page.locator('.queue-item').count(),1);
 await page.locator('#repo-search').fill('');
 checks.push('repository search narrows and restores the example queue');
 await page.locator('#purpose').fill('A deliberately edited illustrative purpose.');
 await page.locator('[data-repo="1"]').click();
 assert.equal(await page.locator('#leave-dialog').isVisible(),true);
 await page.locator('#stay').click();
 assert.equal(await page.locator('#purpose').inputValue(),'A deliberately edited illustrative purpose.');
 checks.push('dirty navigation guard and Keep reviewing preserve edits');
 await page.locator('#open-labels').click();
 await page.locator('#label-search').fill('C technology');
 await page.locator('[data-picker="label"][value="c"]').check();
 await page.locator('#label-dialog').getByRole('button',{name:'Done',exact:true}).click();
 await page.locator('#save-draft').click();
 assert.match(await page.locator('#draft-state').textContent(),/Draft saved in preview/);
 assert.equal(await page.locator('#confirm-next').isDisabled(),true);
 await page.locator('[data-repo="1"]').click();
 await page.locator('[data-repo="0"]').click();
 assert.equal(await page.locator('[data-addquote="c"]').count(),1);
 assert.equal(await page.locator('[data-addquote="c"]').inputValue(),'');
 checks.push('new-label incomplete draft saves separately in memory, restores, and cannot confirm');
 await page.locator('#open-filters').click();
 await page.locator('#filter-search').fill('Scientific');
 await page.locator('[data-picker="filter"][value="scientific"]').check();
 await page.locator('#filter-search').fill('Python');
 await page.locator('[data-picker="filter"][value="python"]').check();
 await page.screenshot({path:path.join(__dirname,'filters-desktop.png')});
 await page.locator('#apply-filters').click();
 assert.equal(await page.locator('.queue-item').count(),2);
 checks.push('searchable proposed multi-facets combine Topic AND Tag');
 await page.reload();
 for(const dimension of ['Project','Topic','Tag'])await page.locator(`[data-dimension="${dimension}"]`).check();
 assert.equal(await page.locator('#confirm-next').isEnabled(),true);
 await page.locator('#confirm-next').click();
 assert.equal(await page.locator('#repo-name').textContent(),'scipy/scipy');
 assert.equal(await page.locator('#confirmed-count').textContent(),'1');
 assert.equal(await page.locator('[data-dimension]:checked').count(),0);
 checks.push('explicit confirmation increments only the simulated record and advances with next checks clear');
 await page.locator('[data-evidence="python"]').click();
 assert.equal(await page.locator('#source-name').textContent(),'GitHub metadata');
 assert.match(await page.locator('.source-code').textContent(),/GITHUB_METADATA/);
 assert.equal(await page.locator('.source-code script').count(),0);
 checks.push('metadata channel stays distinct and source HTML remains plain text');
 assert.deepEqual(externalRequests,[]);
 assert.deepEqual(errors,[]);
 checks.push('zero console/page errors; zero HTTP/API requests');
 fs.writeFileSync(path.join(__dirname,'prototype-checks.json'),JSON.stringify({date:'2026-10-17',result:'passed',checks,errors,externalRequests,scope:'Static illustrative in-memory prototype only; no production app tests or writes'},null,2)+'\n');
 console.log(JSON.stringify({result:'passed',checks},null,2));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
